// Generates public/index.js — the module that public/worker.js imports.
// Combines: the built single-file web app (dist/index.html), the guide/setup
// data from src/content.ts, and the raw source of worker.js itself (served
// back at GET /worker.js so admins can download it).
import { readFileSync, writeFileSync } from 'node:fs';
import { transformSync } from 'esbuild';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const asset = path => {
  if (!path.startsWith('/assets/')) throw new Error('Unexpected build asset: ' + path);
  return readFileSync(resolve('dist', '.' + path), 'utf8');
};
// Inline Vite's own entry assets; no glob dependency or stale committed bundle.
const html = readFileSync('dist/index.html', 'utf8')
  .replace(/<script\b([^>]*)src="(\/assets\/[^"\s]+)"([^>]*)><\/script>/g, (_, before, path, after) => `<script${before}${after}>${asset(path).replace(/<\/script/gi, '<\\/script')}</script>`)
  .replace(/<link\b[^>]*rel="stylesheet"[^>]*href="(\/assets\/[^"\s]+)"[^>]*>/g, (_, path) => `<style>${asset(path)}</style>`);
if (/(?:src|href)="\/assets\//.test(html)) throw new Error('The Worker must serve a self-contained HTML page.');
writeFileSync('dist/index.html', html);
const hashes = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)]
  .filter(([, attrs]) => !/\bsrc=/.test(attrs))
  .map(([, , code]) => `'sha256-${createHash('sha256').update(code).digest('base64')}'`);
const contentSecurityPolicy = `default-src 'none'; script-src 'self' https://telegram.org ${hashes.join(' ')}; style-src 'self' 'unsafe-inline'; img-src 'self' data: https:; media-src https:; font-src 'self' data:; connect-src 'self' https:; frame-src https://www.openstreetmap.org; frame-ancestors 'self' https://web.telegram.org https://*.telegram.org; base-uri 'none'; object-src 'none'; form-action 'none'`;
const workerSource = readFileSync('public/worker.js', 'utf8');

// src/content.ts has no external imports, so it can be transpiled and
// executed standalone to pull out the plain data arrays it exports.
const ts = readFileSync('src/content.ts', 'utf8');
const { code } = transformSync(ts, { loader: 'ts', format: 'cjs' });
const mod = { exports: {} };
new Function('module', 'exports', code)(mod, mod.exports);
const { GUIDES, RELEASES, SETUP } = mod.exports;

const out = `// Auto-generated by scripts/build-worker.mjs — do not edit by hand.
export const guides = ${JSON.stringify(GUIDES)};
export const releases = ${JSON.stringify(RELEASES)};
export const setup = ${JSON.stringify(SETUP)};
export const workerSource = ${JSON.stringify(workerSource)};
export const contentSecurityPolicy = ${JSON.stringify(contentSecurityPolicy)};
export default ${JSON.stringify(html)};
`;

writeFileSync('public/index.js', out);
console.log(`Generated public/index.js (${(out.length / 1024).toFixed(0)} KB)`);
